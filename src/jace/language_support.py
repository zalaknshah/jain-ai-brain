"""Authored Hindi/Gujarati fallback text, not translation or language detection.

The script cue only selects among fixed local templates. Devanagari is shared
by other languages; mixed Gujarati/Devanagari falls back to English. Romanized
language and arbitrary instructions are not interpreted here.
"""
from __future__ import annotations

import unicodedata

from .text import lexical_terms


def script_cues(text: str) -> tuple[bool, bool]:
    letters = [c for c in text if unicodedata.category(c).startswith('L')]
    hindi = any('\u0900' <= c <= '\u097f' for c in letters)
    gujarati = any('\u0a80' <= c <= '\u0aff' for c in letters)
    return hindi, gujarati


def response_language(text: str) -> str:
    hindi, gujarati = script_cues(text)
    if hindi and not gujarati:
        return 'hi'
    if gujarati and not hindi:
        return 'gu'
    return 'en'


